import fs from 'node:fs';
import assert from 'node:assert/strict';
const root = 'reference/web/final-production';
const read = relative => JSON.parse(fs.readFileSync(root + '/' + relative, 'utf8'));
const interaction = read('interactions/report.json');
const state = read('state/report.json');
const filters = read('all-filters/report.json');
const flows = read('filter-flows/filter-report.json');
const visual = read('visual/report.json');
console.log('REPORT_KEYS', Object.keys(interaction), Object.keys(flows));
const cases = interaction.checks;
assert.equal(cases.length, 13);
assert.ok(cases.every(test => test.passed === true || test.pass === true));
assert.equal(state.report.length, 6);
assert.ok(state.report.every(test => test.pass));
assert.equal(filters.report.length, 70);
assert.ok(filters.report.every(test => test.pass));
assert.equal(filters.errors.length, 0);
assert.equal(visual.report.length, 41);
assert.ok(visual.report.every(test => test.status === 200 && !test.error && test.errors.length === 0));
const checks = flows.checks || flows.report;
assert.equal(checks.length, 3);
assert.ok(checks.every(test => test.pass));
assert.equal(flows.errors.length, 0);
console.log('VERIFIED_ACCEPTANCE', JSON.stringify({ interaction: cases.length, state: state.report.length, filterControls: filters.report.length, filterFlows: checks.length, capturedStates: visual.report.length, buildId: fs.readFileSync('.next/BUILD_ID', 'utf8').trim() }));
