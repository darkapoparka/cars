const popularMakes = new Set(['Audi', 'BMW', 'Ford', 'Mercedes-Benz', 'Opel', 'Porsche', 'Skoda', 'Toyota', 'Volkswagen'].map(key));

export const desktopMakeArtwork = (make: string) => artworkByMake.get(key(make));
export const desktopMakeCount = (make: string) => make ? stockByMake.get(key(make)) ?? 0 : featuredVehicles.length;

/** Stock first, then familiar makes, the catalogue and retained selections. */
export function desktopMakeOptions(current: string | readonly string[], locale: Locale): string[] {
  const options = new Map<string, string>();
  for (const make of [...featuredVehicles.map(vehicle => vehicle.make), ...desktopMakeCatalogue, ...listingSelections(current)]) {
    if (!options.has(key(make))) options.set(key(make), make);
  }
  return ['', ...options.values()].sort((a, b) => {
    if (!a || !b) return a ? 1 : b ? -1 : 0;
    const inStock = Number(desktopMakeCount(b) > 0) - Number(desktopMakeCount(a) > 0);
    const popular = Number(popularMakes.has(key(b))) - Number(popularMakes.has(key(a)));
    return inStock || popular || a.localeCompare(b, locale, { numeric: true });
  });
}
