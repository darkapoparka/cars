import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.setDefaultTimeout(10000);
const report=[];
async function open(route='') {
  await page.goto('http://127.0.0.1:6430/'+route,{waitUntil:'load'});
  await page.waitForFunction(()=>document.documentElement.dataset.rencarReady==='true');
  await page.evaluate(()=>document.fonts.ready);
  await page.locator('.preloader').waitFor({state:'hidden'});
}
await open();
await page.locator('.nav-right .search-box-outer').click();
assert(await page.locator('body').evaluate(e=>e.classList.contains('search-active')));
assert(await page.locator('.search-popup input').evaluate(e=>e===document.activeElement));
await page.keyboard.press('Escape');
assert(await page.locator('.nav-right .search-box-outer').evaluate(e=>e===document.activeElement));
report.push('Search opens, focuses field, closes with Escape, returns focus');
await page.locator('.sidebar-btn').click();
await page.locator('#sidebarPopup.show').waitFor();
await page.keyboard.press('Escape');
await page.locator('#sidebarPopup.show').waitFor({state:'hidden'});
report.push('Information drawer opens and closes with Escape');
await page.locator('.hero-slider').evaluate(el=>window.jQuery(el).trigger('stop.owl.autoplay'));
const before=await page.locator('.hero-slider').evaluate(el=>window.jQuery(el).data('owl.carousel').relative(window.jQuery(el).data('owl.carousel').current()));
await page.locator('.hero-slider .owl-next').click();
const after=await page.locator('.hero-slider').evaluate(el=>window.jQuery(el).data('owl.carousel').relative(window.jQuery(el).data('owl.carousel').current()));
assert.notEqual(before,after);
report.push('Hero carousel next control changes slide');
await page.locator('.ss-main').first().click();
await page.locator('.ss-option:visible').filter({hasText:'Brooklyn, New York'}).click();
assert.match(await page.locator('.ss-main').first().innerText(),/Brooklyn/);
await page.locator('.date-picker').first().click();
await page.locator('.flatpickr-calendar.open').waitFor();
await page.locator('.flatpickr-calendar.open .flatpickr-day:not(.prevMonthDay):not(.nextMonthDay)').filter({hasText:/^15$/}).click();
await page.keyboard.press('Escape');
assert(await page.locator('.date-picker').first().inputValue());
report.push('Location selector and date/time picker accept selections');
await page.getByRole('button',{name:/Book Car/}).click();
await page.waitForURL('**/car-booking.html');
await page.waitForFunction(()=>document.documentElement.dataset.rencarReady==='true');
report.push('Homepage booking form opens car booking page');
await open('faq.html');
await page.locator('[data-bs-target="#collapseTwo"]').click();
await page.locator('#collapseTwo.show').waitFor();
report.push('FAQ accordion expands selected answer');
await page.setViewportSize({width:390,height:844});
await open();
await page.locator('.navbar-toggler').click();
await page.locator('#offcanvasNavbar.show').waitFor();
await page.locator('#offcanvasNavbar .nav-link').filter({hasText:/^Cars$/}).click();
await page.locator('#offcanvasNavbar .dropdown-item').filter({hasText:/^Cars One$/}).click();
await page.waitForURL('**/car.html');
await page.waitForFunction(()=>document.documentElement.dataset.rencarReady==='true');
report.push('Mobile menu opens, expands Cars, navigates to listing');
await page.locator('.car-item a[href="/car-single.html"]').first().click();
await page.waitForURL('**/car-single.html');
report.push('Car listing opens car detail');
await page.goBack();
await page.waitForURL('**/car.html');
report.push('Browser back returns to listing');
await writeFile('reference/qa/interaction-report.json',JSON.stringify(report,null,2));
console.log(report.join('\n'));
await browser.close();
