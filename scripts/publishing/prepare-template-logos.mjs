import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';

const root = path.resolve(import.meta.dirname, '../..');
const require = createRequire(path.join(root, 'templates/karento-best/package.json'));
const sharp = require('sharp');
const catalog = {
  'auto-best': 'templates/auto-best/static/assets/images/template/auto-best-logo-v2.webp',
  modern: 'templates/modern/apps/web/public/images/brand/modern-logo-v2.webp',
  import: 'templates/import/static/brand/import-logo-v2.webp',
  app: 'templates/app/public/identity/drive24/logo-light-v2.webp',
  mobile: 'templates/mobile/public/branding/showroom-compact-20261005.webp',
  'karento-best': 'templates/karento-best/static/brand/signature-logo-v1.webp',
};
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const write = process.argv.includes('--write');
const directory = path.join(import.meta.dirname, 'design-logos');
const logos = {};
const evidence = [];
for (const [key, source] of Object.entries(catalog)) {
  const original = await fs.readFile(path.join(root, source));
  const { data, info } = await sharp(original)
    .trim({ background: { r: 0, g: 0, b: 0, alpha: 0 }, threshold: 1 })
    .resize({ width: 360, withoutEnlargement: true })
    .webp({ lossless: true, effort: 6 })
    .toBuffer({ resolveWithObject: true });
  const destination = path.join(directory, `${key}.webp`);
  if (write) {
    await fs.mkdir(directory, { recursive: true });
    await fs.writeFile(destination, data);
  } else if (!(await fs.readFile(destination)).equals(data)) {
    throw new Error(`Selector logo differs from its recorded template: ${key}`);
  }
  logos[key] = `data:image/webp;base64,${data.toString('base64')}`;
  evidence.push({ key, source, sourceSha256: sha256(original), sha256: sha256(data), width: info.width, height: info.height, bytes: data.length });
}
const filename = path.join(import.meta.dirname, 'preview-switcher.js');
const source = await fs.readFile(filename, 'utf8');
const boundary = /\/\* START TEMPLATE LOGOS: generated by prepare-template-logos\.mjs \*\/[\s\S]*?\/\* END TEMPLATE LOGOS \*\//g;
if ([...source.matchAll(boundary)].length !== 1) throw new Error('Unknown selector logo boundary');
const replacement = `/* START TEMPLATE LOGOS: generated by prepare-template-logos.mjs */\n  const templateLogos = ${JSON.stringify(logos)};\n  /* END TEMPLATE LOGOS */`;
const updated = source.replace(boundary, () => replacement);
if (write) {
  await fs.writeFile(filename, updated);
  await fs.writeFile(path.join(directory, 'provenance.json'), JSON.stringify({ schemaVersion: 1, encoding: 'lossless-webp', evidence }, null, 2) + '\n');
} else if (updated !== source) {
  throw new Error('Bundled selector logo bytes differ from its reviewed assets');
}
console.log(JSON.stringify({ mode: write ? 'written' : 'verified', logos: evidence.length, bytes: evidence.reduce((sum, item) => sum + item.bytes, 0) }));
